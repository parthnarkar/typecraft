import mongoose from "mongoose";

const employeeSchema = new mongoose.Schema({
    employeeId: {
        type: Number,
        required: true,
        unique: true
    },
    name: {
        type: String,
        required: true,
        trim: true,
    },
    department: {
        type: String,
        required: true,
        trim: true
    },
    salary: {
        type: Number,
        required: true,
        min: 0
    },
    status: {
        type: String,
        enum: ['active', 'inactive'],
        default: 'active',
        required: true
    }
});

const Employee = mongoose.model('Employee', employeeSchema);

export default Employee;